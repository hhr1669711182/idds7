    let ret =
      -100.0 +
      2.0 * x +
      3.0 * y +
      0.2 * y * y +
      0.1 * x * y +
      0.2 * Math.sqrt(Math.abs(x));
    ret += (20.0 * Math.sin(6.0 * x * PI) + 20.0 * Math.sin(2.0 * x * PI)) * (2.0 / 3.0);
    ret += (20.0 * Math.sin(y * PI) + 40.0 * Math.sin((y * PI) / 3.0)) * (2.0 / 3.0);
